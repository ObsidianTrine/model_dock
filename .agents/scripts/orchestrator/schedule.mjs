// schedule.mjs — nightly 定时调度的三平台注册（macOS launchd / Linux crontab / Windows schtasks）。
// 设计：调度器只负责定时拉起一个 wrapper 脚本（.agents/orchestrator/nightly-runner.sh|cmd），
// wrapper 内编码仓库绝对路径、node 绝对路径与 nightly 参数——launchd/schtasks 的执行环境
// PATH 极瘦（git 都可能不在），绝不能依赖环境发现，install 时刻全部解析成绝对路径固化。
//
// 纯函数（build*）与执行层（install/uninstall/status）分离：测试只测纯函数与 --dry-run，
// 绝不真注册开发机的 launchd/crontab/schtasks。

import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

export const SCHEDULE_ID = 'com.modeldock.orchestrator-nightly';
const WIN_TASK_NAME = 'ModelDock Orchestrator Nightly';
const CRON_BEGIN = `# BEGIN ${SCHEDULE_ID}`;
const CRON_END = `# END ${SCHEDULE_ID}`;

export function runnerPath(repoRoot) {
  return path.join(repoRoot, '.agents', 'orchestrator', process.platform === 'win32' ? 'nightly-runner.cmd' : 'nightly-runner.sh');
}

export function nightlyLogPath(repoRoot) {
  return path.join(repoRoot, '.agents', 'orchestrator', 'logs', 'nightly.log');
}

/**
 * nightly CLI 参数（nightly/schedule install 共用一份拼装，保证 wrapper 与手动跑行为一致）。
 * opts: { tests, auto, backend, reviewBackend }
 */
export function nightlyArgs(opts = {}) {
  const args = ['nightly'];
  if (opts.tests) args.push('--tests');
  if (Number.isInteger(opts.auto) && opts.auto > 0) args.push('--auto', String(opts.auto));
  if (opts.backend) args.push('--backend', opts.backend);
  if (opts.reviewBackend) args.push('--review-backend', opts.reviewBackend);
  return args;
}

/** unix wrapper 内容（\n 换行）。exec 由调用方 /bin/sh 执行，无需依赖可执行位。 */
export function buildRunnerUnix(repoRoot, nodePath, args) {
  const log = nightlyLogPath(repoRoot);
  return [
    '#!/bin/sh',
    `# ${SCHEDULE_ID} wrapper（schedule install 生成；重装请跑 orchestrator.mjs schedule install）`,
    `cd "${repoRoot}" || exit 1`,
    `exec "${nodePath}" "${path.join(repoRoot, '.agents', 'scripts', 'orchestrator.mjs')}" ${args.join(' ')} >> "${log}" 2>&1`,
    '',
  ].join('\n');
}

/** Windows wrapper 内容（\r\n 换行；cd /d 跨盘符）。 */
export function buildRunnerWin(repoRoot, nodePath, args) {
  const log = nightlyLogPath(repoRoot);
  const lines = [
    '@echo off',
    `rem ${SCHEDULE_ID} wrapper (generated by schedule install)`,
    `cd /d "${repoRoot}" || exit /b 1`,
    `"${nodePath}" "${path.join(repoRoot, '.agents', 'scripts', 'orchestrator.mjs')}" ${args.join(' ')} >> "${log}" 2>&1`,
    '',
  ];
  return lines.join('\r\n');
}

/** macOS launchd plist 内容。ProgramArguments 用 /bin sh 显式解释 wrapper（不依赖 chmod +x）。 */
export function buildPlist(repoRoot, { hour, minute }) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${SCHEDULE_ID}</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/sh</string>
    <string>${runnerPath(repoRoot)}</string>
  </array>
  <key>WorkingDirectory</key><string>${repoRoot}</string>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Hour</key><integer>${hour}</integer>
    <key>Minute</key><integer>${minute}</integer>
  </dict>
  <key>StandardOutPath</key><string>${nightlyLogPath(repoRoot)}</string>
  <key>StandardErrorPath</key><string>${nightlyLogPath(repoRoot)}</string>
</dict>
</plist>
`;
}

export function plistPath() {
  return path.join(os.homedir(), 'Library', 'LaunchAgents', `${SCHEDULE_ID}.plist`);
}

/** Linux crontab 标记段内容（install 时整段替换，天然幂等）。 */
export function buildCronBlock(repoRoot, { hour, minute }) {
  const line = `${minute} ${hour} * * * /bin/sh "${runnerPath(repoRoot)}"`;
  return `${CRON_BEGIN}\n${line}\n${CRON_END}`;
}

/** Windows schtasks 创建参数（/TR 值带内层引号，仓库路径含空格也正确）。 */
export function buildSchtasksCreateArgs(repoRoot, { hour, minute }) {
  return [
    '/Create', '/F',
    '/TN', WIN_TASK_NAME,
    '/SC', 'DAILY',
    '/ST', `${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}`,
    '/TR', `"${runnerPath(repoRoot)}"`,
  ];
}

export function buildSchtasksDeleteArgs() {
  return ['/Delete', '/F', '/TN', WIN_TASK_NAME];
}

// ---------------------------------------------------------------------------
// 执行层
// ---------------------------------------------------------------------------

function writeRunner(repoRoot, args) {
  fs.mkdirSync(path.dirname(runnerPath(repoRoot)), { recursive: true });
  fs.mkdirSync(path.dirname(nightlyLogPath(repoRoot)), { recursive: true });
  const content = process.platform === 'win32' ? buildRunnerWin(repoRoot, process.execPath, args) : buildRunnerUnix(repoRoot, process.execPath, args);
  fs.writeFileSync(runnerPath(repoRoot), content);
  if (process.platform !== 'win32') {
    try {
      fs.chmodSync(runnerPath(repoRoot), 0o755);
    } catch {
      // chmod 失败不阻断：plist/cron 都经 /bin/sh 显式解释，可执行位非必需
    }
  }
}

/** 校验调度时刻参数（CLI 层已解析，这里再守一道：dry-run 与测试复用）。 */
export function validHourMinute(hour, minute) {
  return Number.isInteger(hour) && hour >= 0 && hour <= 23 && Number.isInteger(minute) && minute >= 0 && minute <= 59;
}

/**
 * 安装 nightly 调度。opts: { hour, minute, tests, auto, backend, dryRun }
 * dryRun：写 runner（仓库内无害产物）并打印将执行的注册命令，不触碰系统调度。
 */
export function installSchedule(repoRoot, opts = {}) {
  const hour = opts.hour ?? 2;
  const minute = opts.minute ?? 30;
  if (!validHourMinute(hour, minute)) throw new Error(`调度时刻不合法：hour=${hour} minute=${minute}（hour 0-23、minute 0-59）`);
  const args = nightlyArgs(opts);
  writeRunner(repoRoot, args);

  const plat = process.platform;
  const when = `${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}`;
  if (opts.dryRun) {
    const plan =
      plat === 'darwin'
        ? `写 ${plistPath()} 并 launchctl load（每天 ${when}）`
        : plat === 'win32'
          ? `schtasks ${buildSchtasksCreateArgs(repoRoot, { hour, minute }).join(' ')}`
          : `crontab 追加标记段（每天 ${when}）：\n${buildCronBlock(repoRoot, { hour, minute })}`;
    return { dryRun: true, runner: runnerPath(repoRoot), plan };
  }

  if (plat === 'darwin') {
    fs.mkdirSync(path.dirname(plistPath()), { recursive: true });
    fs.writeFileSync(plistPath(), buildPlist(repoRoot, { hour, minute }));
    execFileSync('launchctl', ['unload', plistPath()], { stdio: 'ignore' }); // 幂等重装：先卸旧（未装时失败忽略）
    execFileSync('launchctl', ['load', plistPath()], { stdio: 'inherit' });
    return { runner: runnerPath(repoRoot), plist: plistPath(), when };
  }
  if (plat === 'win32') {
    const r = spawnSync('schtasks', buildSchtasksCreateArgs(repoRoot, { hour, minute }), { encoding: 'utf8' });
    if (r.status !== 0) throw new Error(`schtasks 注册失败：${(r.stderr || r.stdout || '').trim()}`);
    return { runner: runnerPath(repoRoot), when };
  }
  // Linux：读旧 crontab → 剔除旧标记段 → 追加新段 → 写回
  const cur = spawnSync('crontab', ['-l'], { encoding: 'utf8' });
  const lines = cur.status === 0 ? (cur.stdout || '').split('\n') : [];
  const cleaned = [];
  let inBlock = false;
  for (const l of lines) {
    if (l.trim() === CRON_BEGIN) { inBlock = true; continue; }
    if (l.trim() === CRON_END) { inBlock = false; continue; }
    if (!inBlock) cleaned.push(l);
  }
  while (cleaned.length && cleaned[cleaned.length - 1].trim() === '') cleaned.pop();
  const next = `${cleaned.join('\n').replace(/\n*$/, '')}\n${buildCronBlock(repoRoot, { hour, minute })}\n`;
  const w = spawnSync('crontab', ['-'], { input: next, encoding: 'utf8' });
  if (w.status !== 0) throw new Error(`crontab 写入失败：${(w.stderr || '').trim()}`);
  return { runner: runnerPath(repoRoot), when };
}

/** 卸载调度（runner 文件保留——重新 install 复用，删除仓库内文件交给 reset 类命令）。 */
export function uninstallSchedule() {
  const plat = process.platform;
  if (plat === 'darwin') {
    try {
      execFileSync('launchctl', ['unload', plistPath()], { stdio: 'ignore' });
    } catch {}
    const existed = fs.existsSync(plistPath());
    if (existed) fs.rmSync(plistPath());
    return { removed: existed };
  }
  if (plat === 'win32') {
    const r = spawnSync('schtasks', buildSchtasksDeleteArgs(), { encoding: 'utf8' });
    return { removed: r.status === 0 };
  }
  const cur = spawnSync('crontab', ['-l'], { encoding: 'utf8' });
  if (cur.status !== 0) return { removed: false };
  const lines = (cur.stdout || '').split('\n');
  const cleaned = [];
  let inBlock = false;
  let removed = false;
  for (const l of lines) {
    if (l.trim() === CRON_BEGIN) { inBlock = true; removed = true; continue; }
    if (l.trim() === CRON_END) { inBlock = false; continue; }
    if (!inBlock) cleaned.push(l);
  }
  if (!removed) return { removed: false };
  const w = spawnSync('crontab', ['-'], { input: `${cleaned.join('\n').replace(/\n*$/, '')}\n`, encoding: 'utf8' });
  if (w.status !== 0) throw new Error(`crontab 写入失败：${(w.stderr || '').trim()}`);
  return { removed: true };
}

/** 查询调度注册状态（只读；platform 分支与 install 一一对应）。 */
export function scheduleStatus(repoRoot) {
  const plat = process.platform;
  const runner = runnerPath(repoRoot);
  const runnerReady = fs.existsSync(runner);
  if (plat === 'darwin') {
    const p = plistPath();
    if (!fs.existsSync(p)) return { installed: false, runnerReady, runner };
    const m = /<key>Hour<\/key><integer>(\d+)<\/integer>/.exec(fs.readFileSync(p, 'utf8'));
    return { installed: true, when: m ? `每天 ${m[1]}:?? ` : '每天（时刻见 plist）', plist: p, runnerReady, runner };
  }
  if (plat === 'win32') {
    const r = spawnSync('schtasks', ['/Query', '/TN', WIN_TASK_NAME], { encoding: 'utf8' });
    return { installed: r.status === 0, runnerReady, runner };
  }
  const cur = spawnSync('crontab', ['-l'], { encoding: 'utf8' });
  const installed = cur.status === 0 && (cur.stdout || '').includes(CRON_BEGIN);
  return { installed, runnerReady, runner };
}
